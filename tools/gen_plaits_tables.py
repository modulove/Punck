#!/usr/bin/env python3
"""Generate Punck/src/third_party/plaits/resources.cc (sine table used by Plaits' SineOscillator).

Plaits defines lut_sine as sin(2*pi*i/512) for i = 0..640 (one full cycle plus a quarter cycle so
cosine lookups can read past the end without wrapping).
"""
import math
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "Punck", "src", "third_party", "plaits", "resources.cc")

values = [math.sin(2 * math.pi * i / 512.0) for i in range(641)]
lines = ["// Generated by tools/gen_plaits_tables.py - do not edit.",
         "// Plaits sine table (c) Emilie Gillet, MIT License.",
         '#include "plaits/resources.h"', "", "namespace plaits {", "", "const float lut_sine[] = {"]
for i in range(0, len(values), 8):
    lines.append("  " + ", ".join(f"{v: .9e}f" for v in values[i:i + 8]) + ",")
lines += ["};", "", "}  // namespace plaits", ""]
open(OUT, "w", newline="\n").write("\n".join(lines))
print(f"wrote {OUT} ({len(values)} values)")
