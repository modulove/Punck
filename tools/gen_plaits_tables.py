#!/usr/bin/env python3
"""Generate Punck/src/third_party/plaits/resources.cc (lookup tables used by the ported Plaits code).

- lut_sine: sin(2*pi*i/512) for i = 0..640 (one full cycle plus a quarter cycle so cosine lookups can read past
  the end without wrapping) - used by Plaits' SineOscillator.
- lut_svf_shift: 1 - 2*atan(1/r)/(2*pi) with r = 2^(i/12), i = 0..256 - delay correction for the string's damping
  filter (plaits/resources/lookup_tables.py, 'svf_shift').
"""
import math
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "Punck", "src", "third_party", "plaits", "resources.cc")

tables = [
    ("lut_sine", [math.sin(2 * math.pi * i / 512.0) for i in range(641)]),
    ("lut_svf_shift", [1.0 - 2.0 * math.atan(1.0 / 2.0 ** (i / 12.0)) / (2.0 * math.pi) for i in range(257)]),
]
lines = ["// Generated by tools/gen_plaits_tables.py - do not edit.",
         "// Plaits lookup tables (c) Emilie Gillet, MIT License.",
         '#include "plaits/resources.h"', "", "namespace plaits {", ""]
for name, values in tables:
    lines.append(f"const float {name}[] = {{")
    for i in range(0, len(values), 8):
        lines.append("  " + ", ".join(f"{v: .9e}f" for v in values[i:i + 8]) + ",")
    lines += ["};", ""]
lines += ["}  // namespace plaits", ""]
open(OUT, "w", newline="\n").write("\n".join(lines))
print(f"wrote {OUT} (" + ", ".join(f"{n} {len(v)}" for n, v in tables) + ")")
