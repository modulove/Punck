#!/usr/bin/env python3
"""Generate Punck/src/third_party/plaits/resources.cc (lookup tables used by the ported Plaits code).

Same formulas as plaits/resources/lookup_tables.py (Emilie Gillet, MIT licence), in plain Python (no numpy):
- lut_sine: sin(2*pi*i/512), i = 0..640 - SineOscillator, SinePM
- lut_svf_shift: 1 - 2*atan(1/r)/(2*pi), r = 2^(i/12), i = 0..256 - string damping filter delay correction
- lut_fm_frequency_quantizer: FM engine ratio quantizer (semitones), 130 entries
- lut_ws_*: waveshaper tables (int16, 257 entries) for the waveshaping engine, lookup_table_i16_table order
- lut_fold, lut_fold_2: wavefolder curves (516 entries)
- lut_4x_downsampler_fir: FM engine 4x downsampler
"""
import math
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT_CC = os.path.join(ROOT, "Punck", "src", "third_party", "plaits", "resources.cc")
OUT_H = os.path.join(ROOT, "Punck", "src", "third_party", "plaits", "resources.h")

tables = []          # (name, values) float
tables_i16 = []      # (name, values) int16

# Sine
tables.append(("lut_sine", [math.sin(2 * math.pi * i / 512.0) for i in range(641)]))

# SVF shift (string)
tables.append(("lut_svf_shift", [1.0 - 2.0 * math.atan(1.0 / 2.0 ** (i / 12.0)) / (2.0 * math.pi) for i in range(257)]))

# Quantizer for FM frequencies
ratios = [0.5, 0.5 * 2 ** (16 / 1200.0), math.sqrt(2) / 2, math.pi / 4, 1.0, 1.0 * 2 ** (16 / 1200.0), math.sqrt(2),
          math.pi / 2, 7.0 / 4, 2, 2 * 2 ** (16 / 1200.0), 9.0 / 4, 11.0 / 4, 2 * math.sqrt(2), 3, math.pi,
          math.sqrt(3) * 2, 4, math.sqrt(2) * 3, math.pi * 3 / 2, 5, math.sqrt(2) * 4, 8]
scale = []
for r in ratios:
    st = 12 * math.log2(r)
    scale.extend([st, st, st])
target = int(2 ** math.ceil(math.log2(len(scale))))
while len(scale) < target:
    diffs = [scale[i + 1] - scale[i] for i in range(len(scale) - 1)]
    gap = max(range(len(diffs)), key=lambda i: (diffs[i], -i))      # numpy.argmax: first maximum
    scale = scale[:gap + 1] + [(scale[gap] + scale[gap + 1]) / 2] + scale[gap + 1:]
scale += [scale[-1], scale[-1]]
tables.append(("lut_fm_frequency_quantizer", scale))

# Waveshaper tables (Tides)
N = 128
x = [i / float(N) for i in range(N + 1)]
tanv = [math.atan(8 * math.cos(math.pi * v)) for v in x]
tscale = max(tanv)
fade_crop = [min(1.0, 4.0 - 4.0 * v) for v in x]
linear = x
bump = [(1.0 - math.cos(math.pi * v * 1.5)) * (1.0 - math.cos(math.pi * fc)) / 4.5 for v, fc in zip(x, fade_crop)]
double_bump = [math.sin(math.pi * v * 1.5) for v in x]
inverse_sin = [math.acos(1 - 2 * v) / math.pi for v in x]
inverse_tan = [math.acos(math.tan(tscale * (1.0 - 2.0 * v)) / 8.0) / math.pi for v in x]


def flip(t):
    full = [-t[i] for i in range(N, 0, -1)] + list(t)
    return [int(round(v * 32767.0)) for v in full]


for name, t in (("lut_ws_inverse_tan", inverse_tan), ("lut_ws_inverse_sin", inverse_sin), ("lut_ws_linear", linear),
                ("lut_ws_bump", bump), ("lut_ws_double_bump", double_bump), ("lut_ws_double_bump_sentinel", double_bump)):
    tables_i16.append((name, flip(t)))

# Wavefolders
W = 512
x = [i / (W / 2.0) - 1.0 for i in range(W + 4)]
x[-1] = x[-2]
fold = []
for v in x:
    window = math.exp(-v * v * 4) ** 2
    fold.append(math.sin(8 * math.pi * v) * window + math.atan(3 * v) * (1 - window))
m = max(abs(v) for v in fold)
tables.append(("lut_fold", [v / m for v in fold]))


def deadband(v_in, r_in, r_load, r_fb=150.0e3, v_sat=10.47):
    out = []
    for vi in v_in:
        vo = -r_fb / r_in * vi
        vo = min(max(vo, -v_sat), v_sat) if vo < v_sat else v_sat
        out.append((vi * r_fb * r_load + vo * r_in * r_load) / (r_fb * r_load + r_in * r_load + r_in * r_fb))
    return out


def diode(v):
    return 0.7 * v / (0.3 + abs(v))


v_in = [v * 12.0 for v in x]
s1 = deadband(v_in, 10e3, 100e3)
s2 = deadband(v_in, 49.9e3, 44.2e3)
s3 = deadband(v_in, 91e3, 18e3)
s4 = deadband(v_in, 30e3, 71.4e3)
s5 = deadband(v_in, 68e3, 33.0e3)
s45 = [-33.0 / 71.4 * a - 33.0 / 33.0 * b - 33.0 / 240.0 * c for a, b, c in zip(s4, s5, v_in)]
v_out = [diode(-150.0 / 100.0 * a - 150.0 / 44.2 * b - 150.0 / 18.0 * c - 150.0 / 33.0 * d) for a, b, c, d in zip(s1, s2, s3, s45)]
m = max(v_out)
tables.append(("lut_fold_2", [v / m for v in v_out]))

# 4x downsampler (FM engine)
tables.append(("lut_4x_downsampler_fir", [0.02442415, 0.09297315, 0.16712938, 0.21547332]))

# Tables read every sample by the audio interrupt: copied to DTCM at start-up (.data) - from flash they miss the
# D-cache, which the reverb buffers keep flushing (FM reads the sine table 16 times per sample)
FAST = {"lut_sine", "lut_4x_downsampler_fir", "lut_fold", "lut_fm_frequency_quantizer"} | {n for n, _ in tables_i16}

# --- resources.cc
lines = ["// Generated by tools/gen_plaits_tables.py - do not edit.",
         "// Plaits lookup tables (c) Emilie Gillet, MIT License.",
         '#include "plaits/resources.h"', "",
         "#ifdef TEST",
         "#define FAST_TABLE",
         "#else",
         '#define FAST_TABLE __attribute__((section(".data.plaits_tables")))	// DTCM, copied from flash at start-up',
         "#endif", "", "namespace plaits {", ""]
for name, values in tables:
    lines.append(f"{'FAST_TABLE ' if name in FAST else ''}const float {name}[] = {{")
    for i in range(0, len(values), 8):
        lines.append("  " + ", ".join(f"{v: .9e}f" for v in values[i:i + 8]) + ",")
    lines += ["};", ""]
for name, values in tables_i16:
    lines.append(f"{'FAST_TABLE ' if name in FAST else ''}const int16_t {name}[] = {{")
    for i in range(0, len(values), 12):
        lines.append("  " + ", ".join(f"{v:6d}" for v in values[i:i + 12]) + ",")
    lines += ["};", ""]
lines.append("FAST_TABLE const int16_t* const lookup_table_i16_table[] = {")
lines += [f"  {name}," for name, _ in tables_i16]
lines += ["};", "", "}  // namespace plaits", ""]
open(OUT_CC, "w", newline="\n").write("\n".join(lines))

# --- resources.h
h = ["// Trimmed for Punck (modulove fork): only the tables used by the ported code. Generated by",
     "// tools/gen_plaits_tables.py - do not edit. Original: Copyright 2016 Emilie Gillet, MIT License (see third_party/LICENSE).",
     "", "#ifndef PLAITS_RESOURCES_H_", "#define PLAITS_RESOURCES_H_", "", '#include "stmlib/stmlib.h"', "",
     "namespace plaits {", ""]
for name, values in tables:
    h.append(f"extern const float {name}[];")
for name, values in tables_i16:
    h.append(f"extern const int16_t {name}[];")
h += ["extern const int16_t* const lookup_table_i16_table[];", ""]
for i, (name, values) in enumerate(tables + tables_i16):
    tag = name.upper()
    h.append(f"#define {tag} {i}")
    h.append(f"#define {tag}_SIZE {len(values)}")
h += ["", "}  // namespace plaits", "", "#endif  // PLAITS_RESOURCES_H_", ""]
open(OUT_H, "w", newline="\n").write("\n".join(h))
print("wrote resources.cc / .h: " + ", ".join(f"{n} {len(v)}" for n, v in tables + tables_i16))
